import assert from 'node:assert/strict';
import {SEED,figures} from './fixtures/demo.js';
import {ensureProfiles} from '../dist/workspace-model.js';
import {ensureInventory,documentReferences,assetDocuments,assetTasks,assetObligations,obligationDocuments,addReference,requirementStatus,adaptAssetFields,assetFields} from '../dist/inventory-model.js';
const s=structuredClone(SEED);ensureProfiles(s);
const totals=JSON.stringify(figures(s,'aurora','2026-07'));
const originalDocs=structuredClone(s.documents);ensureInventory(s);
assert.deepEqual(s.documents.slice(0,originalDocs.length),originalDocs);
assert.equal(JSON.stringify(figures(s,'aurora','2026-07')),totals);
const a=s.assets.find(x=>x.id==='a204'),water=s.documents.find(x=>x.id==='dwater');
const refs=documentReferences(s,water);
assert(refs.some(r=>r.kind==='obligation'&&r.id==='o204'&&r.via.some(t=>t.includes('Participação na água'))));
assert(refs.some(r=>r.kind==='asset'&&r.id==='a204'&&r.purpose==='support'&&!r.direct));
assert(!refs.some(r=>r.kind==='asset'&&r.purpose==='documentation'));
assert(refs.some(r=>r.kind==='obligation'&&r.label.includes('07/2026')));
assert(assetDocuments(s,a,'support').some(d=>d.id==='dreceipt'));
assert(!assetDocuments(s,a,'documentation').some(d=>d.id==='dreceipt'));
assert(assetDocuments(s,a,'documentation').some(d=>d.id==='dcontract'));
assert(assetTasks(s,a).some(t=>t.id==='trateio'));
assert(assetObligations(s,s.assets.find(x=>x.id==='hdesk')).some(o=>o.id==='oh'));
assert.throws(()=>addReference(s,water,{kind:'asset',id:'hdesk',purpose:'documentation'}));
addReference(s,water,{kind:'asset',id:'a204',purpose:'support',note:'Conferir 20%'});
addReference(s,water,{kind:'asset',id:'a204',purpose:'support',note:'Atualizado'});
assert.equal(water.references.length,1);
assert.equal(water.references[0].note,'Atualizado');
addReference(s,water,{kind:'asset',id:'a105',purpose:'support'});
assert(assetDocuments(s,s.assets.find(x=>x.id==='a105'),'support').some(d=>d.id==='dwater'));
const doc=s.documents.find(x=>x.id==='asset-acar-identification');
addReference(s,doc,{kind:'obligation',id:'ocar',purpose:'documentation'});
assert.equal(doc.references.at(-1).purpose,'support');
assert(obligationDocuments(s,s.obligations.find(x=>x.id==='ocar')).some(d=>d.id===doc.id));
assert.equal(requirementStatus(s,{doc:'not-here'},'2026-07-18').label,'Falta documento');
assert.equal(requirementStatus(s,{doc:'dlocked'},'2026-07-18').label,'Aguardando senha');
assert.equal(requirementStatus(s,{doc:'dcontract',validUntil:'2026-07-17'},'2026-07-18').tone,'red');
assert.equal(requirementStatus(s,{doc:'dcontract',validUntil:'2026-07-18'},'2026-07-18').tone,'green');
assert.equal(requirementStatus(s,{doc:'dpartial'},'2026-07-18').label,'A conferir');
a.dossier.attributes.push({label:'Condição personalizada',value:'Preservar'});
const snapshot=JSON.stringify(s);ensureInventory(s);assert.equal(JSON.stringify(s),snapshot);
assert.equal(JSON.stringify(figures(s,'aurora','2026-07')),totals);
console.log('Verified reference provenance, shared documents, company isolation, period labels, asset inheritance, editable field preservation and independent financial/document states.');

const equipment=adaptAssetFields(assetFields('Imóvel'),'Equipamento','Imóvel');assert.equal(equipment.length,4);assert(!equipment.some(f=>f.label==='Área'));
const migrated=adaptAssetFields([{label:'Área',value:'80 m²'},{label:'Etiqueta própria',value:''}],'Equipamento','Imóvel');assert(migrated.some(f=>f.value==='80 m²'));assert(migrated.some(f=>f.label==='Etiqueta própria'));
