import assert from 'node:assert/strict';
import {SEED,figures} from './fixtures/demo.js';
import {dailyBook,monthDays,contractTemplate,workbookPeriods,summarizePeriods} from '../dist/workbook-model.js';

const days=dailyBook(SEED,'aurora','2026-07');
assert.equal(days.length,31);
assert.equal(days[4].opening,1845000);
assert.equal(days[4].closing,2175000);
assert.equal(days[11].incoming,180000);
assert.equal(days[14].dueIn,240000);
assert.equal(days[14].pendingIn,60000);
assert.equal(days[14].outgoing,120000);
assert.equal(days[17].transactions.length,0);
assert.equal(days[17].tasks.length,2);
for(let i=1;i<days.length;i++)assert.equal(days[i].opening,days[i-1].closing);
assert.equal(days.at(-1).closing,figures(SEED,'aurora','2026-07').balance);
assert.equal(days.reduce((n,d)=>n+d.pendingIn,0),480000);
assert.equal(days.reduce((n,d)=>n+d.pendingOut,0),85000);
assert.equal(dailyBook(SEED,'aurora','2026-07','bb')[11].incoming,0);
assert.equal(dailyBook(SEED,'horizonte','2026-07')[17].tasks.length,0);
assert.equal(monthDays('2028-02').length,29);
assert.equal(monthDays('2027-02').length,28);
const draft=contractTemplate(SEED,'c204','2026-09');
assert.equal(draft.due,'2026-09-05');
assert.equal(draft.items[0].amount,300000);
assert.equal(draft.asset,'a204');
assert.equal(draft.company,'aurora');
assert.equal(draft.valid,true);
assert.equal(contractTemplate(SEED,'c204','2028-01').valid,false);
const snap=structuredClone(SEED);const prior=figures(snap,'aurora','2026-09').balance;
snap.obligations.push({...draft,id:'template-test',docs:[]});
assert.equal(figures(snap,'aurora','2026-09').balance,prior,'Creating a commitment must not create cash');
console.log('Verified daily roll-forward, bank filters, planned vs outstanding amounts, task dates, leap years and contract templates.');

const months=workbookPeriods(SEED,'aurora','2026-07','monthly');
assert.equal(months.length,12);
assert.equal(months[6].incoming,510000);
assert.equal(months[6].outgoing,203000);
assert.equal(months[6].closing,2152000);
assert.equal(months[7].opening,months[6].closing);
assert.equal(months[7].pendingIn,990000);
const year=workbookPeriods(SEED,'aurora','2026-07','yearly')[0];
assert.equal(year.key,'2026');
assert.equal(year.incoming,510000);
assert.equal(year.outgoing,203000);
assert.equal(year.closing,2152000,'Year-end balance must not sum monthly snapshots');
assert.equal(year.pendingIn,1470000);
assert.equal(year.pendingOut,85000);
assert.equal(year.transactions.length,5,'Transactions must occur only once in the annual group');
const week=summarizePeriods(workbookPeriods(SEED,'aurora','2026-07').slice(13,19));
assert.equal(week.opening,1845000+330000-48000+180000);
assert.equal(week.outgoing,120000+35000,'Only payments within the displayed window');
assert.equal(week.closing,2152000);
const multiple=structuredClone(SEED),bradesco=multiple.accounts.find(a=>a.company==='aurora'&&a.id!=='bb').id;
multiple.transactions.push({id:'next-year',account:bradesco,date:'2027-01-02',amount:10000});
multiple.transactions.push({id:'later-year',account:'bb',date:'2028-01-02',amount:-5000});
const years=workbookPeriods(multiple,'aurora','2026-07','yearly');
assert.deepEqual(years.map(y=>y.key),['2026','2027','2028']);
assert.equal(years[1].opening,years[0].closing);
assert.equal(years[1].closing,2162000);
assert.equal(years[2].closing,2157000);
assert.equal(summarizePeriods(years).incoming,520000);
assert.equal(workbookPeriods(multiple,'aurora','2027-01','yearly','bb').find(y=>y.key==='2027').incoming,0);
assert.deepEqual(workbookPeriods(multiple,'horizonte','2026-07','yearly').map(y=>y.key),['2026']);
assert.equal(workbookPeriods(SEED,'aurora','2028-02','monthly')[1].end,'2028-02-29');
console.log('Verified monthly/annual aggregation, closing snapshots, window totals, year boundaries and company/account isolation.');
