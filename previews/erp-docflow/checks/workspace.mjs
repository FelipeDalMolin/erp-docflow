import assert from 'node:assert/strict';
import {SEED,figures} from './fixtures/demo.js';
import {calendarCells,calendarEvents,ensureProfiles} from '../dist/workspace-model.js';

const state=structuredClone(SEED),financial=JSON.stringify([state.transactions,state.obligations,state.accounts]);
const originalDocs=structuredClone(state.documents),originalTasks=structuredClone(state.tasks);
ensureProfiles(state);
assert.equal(JSON.stringify([state.transactions,state.obligations,state.accounts]),financial);
assert.deepEqual(state.documents.slice(0,originalDocs.length),originalDocs);
assert.deepEqual(state.tasks,originalTasks);
const count=state.documents.length;state.companies[0].profile.purpose='User edit';ensureProfiles(state);
assert.equal(state.documents.length,count);assert.equal(state.companies[0].profile.purpose,'User edit');
const cells=calendarCells('2026-07');
assert.equal(cells[0].date,'2026-06-29');assert.equal(cells.length,35);
assert.equal(cells.filter(c=>c.inMonth).length,31);
assert.equal(calendarCells('2028-02').filter(c=>c.inMonth).length,29);
const events=calendarEvents(state,'aurora','2026-07');
assert.equal(events.filter(e=>e.type==='realized').length,5);
assert.equal(events.filter(e=>e.type==='obligation').length,8,'Settled items with unresolved documentation remain visible');
assert.equal(events.filter(e=>e.type==='task').length,4);
assert.equal(events.find(e=>e.id==='due:o105').amount,60000);
assert.equal(events.find(e=>e.id==='due:o105').date,'2026-07-15');
assert.equal(events.find(e=>e.id==='movement:m3').date,'2026-07-12');
assert.ok(events.find(e=>e.id==='due:o204').presentation.warnings.length,'Settled obligations with pending review remain visible');
assert.ok(calendarEvents(state,'aurora','2026-07',{completed:true}).some(e=>e.id==='due:o204'));
assert.equal(calendarEvents(state,'aurora','2026-07',{realized:false,obligation:false}).length,4);
state.tasks.find(t=>t.id==='tmatch').done=true;
assert.ok(!calendarEvents(state,'aurora','2026-07').some(e=>e.id==='task:tmatch'));
assert.ok(calendarEvents(state,'aurora','2026-07',{completed:true}).find(e=>e.id==='task:tmatch').done);
assert.equal(figures(state,'aurora','2026-07').balance,2152000);
assert.equal(calendarEvents(state,'horizonte','2026-07').filter(e=>e.type==='task').length,1);
assert.ok(calendarEvents(state,'horizonte','2026-07').every(e=>!e.title.includes('Sala 204')));
console.log('Verified calendar dates, independent event types, completion filters, company isolation and non-destructive profile migration.');
